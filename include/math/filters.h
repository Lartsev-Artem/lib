#include <stdlib.h>
#include <memory.h>
template<typename data_type, typename filter_type>
class FilterClass
{
public:
	
	FilterClass() :m_length(0), m_filter(nullptr), m_buf(nullptr), m_generic_fir(nullptr)
	{
	}

	void Update(data_type* dst, const data_type* src, int len)
	{
		m_generic_fir(dst, src, len, m_filter, m_length, m_buf);
	}

	void Init(const filter_type* data_filter,  const int len, void (*gen_fir)(data_type*, const data_type*, int, const filter_type*, int, data_type*))
	{
		if (m_length)
		{
			Clear();
		}

		m_filter = (filter_type*)malloc(sizeof(filter_type) * len);
		memcpy(m_filter, data_filter, sizeof(filter_type) * len);
		m_length = len;
		
		m_buf = (data_type*)malloc(sizeof(data_type) * len);
		memset(m_buf, 0, sizeof(data_type) * len);

		m_generic_fir = gen_fir;
	}

	void Clear()
	{
		m_length = 0;
		m_generic_fir = nullptr;

		if (m_filter)
		{
			free(m_filter);
			m_filter = nullptr;
		}

		if (m_buf)
		{
			free(m_buf);
			m_buf = nullptr;
		}		
	}

private:
	int m_length;
	filter_type* m_filter;
	data_type* m_buf;
	void (*m_generic_fir)(data_type*, const data_type*, int, const filter_type*, int, data_type*);	
};